export function fallbackMonologue(kind, userInput = '') {
  const compactInput = String(userInput || '').replace(/\s+/g, ' ').slice(0, 80)
  if (kind === 'monologue1') {
    return `那个名字，回来吧……旧日的人，这次算我求你。你在哪儿？回来，好吗？门外的人，你……`
  }
  if (kind === 'monologue2') {
    return `站住！看着它！抓紧！退后！别松手！撕开！停！再来！闭上眼！往前！往下！不要躲！听！转身！抱住！推开！停！不要停！`
  }
  return `这些词我先收下。${compactInput || '你们留下了水、地面、屋顶和身边的东西'}。我把它们一件一件摆好，让可以承重的成为地面，让柔软的挡住水，让还在发亮的盖在头顶。再把那个不能说清的东西放在身边。${MONOLOGUE3_FIXED_ENDING}`
}
