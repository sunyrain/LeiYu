export function fallbackMaterials(userContext = {}) {
  const rawItems = String(userContext.floodItem || '')
    .split(/[,，、\s]+/)
    .filter(Boolean)
  const items = [...rawItems, '窗台', '纸船', '毛巾'].slice(0, 3)
  const name = userContext.lovedOneName || '那个名字'

  return {
    imagery: [items[0], items[1], items[2], '半开的门缝'],
    motion: ['轻轻翻身', '绕过门缝', '向上浮起', '慢慢折返'],
    texture: ['柔软', '明亮', '温热'],
    bridges: ['在雨停之前，', '像刚醒来时，', '顺着墙角，'],
    sentences: [`${name}把灯放回掌心`, '房间把呼吸轻轻收好'],
  }
}
